# 青を目指す上でDPは避けて通れない。まず「型」として
# 4つを手に馴染ませ、応用問題は型からの変形と捉える。
#   (1) 0/1ナップサック
#   (2) 個数無制限ナップサック
#   (3) LIS (最長増加部分列) の O(N log N) 解法
#   (4) 部分和問題 (集合で持つDPの入口)
#
# DP設計の口癖 (これを毎回声に出す):
#   「dp[状態] = その状態での最適値(または場合の数)」
#   「状態は何か? 遷移は何か? 初期値はどこか? 答えはどこか?」
# =====================================================

from bisect import bisect_left


# -----------------------------------------------------
# (1) 0/1ナップサック: 各品物は1回しか使えない
#   dp[w] = 重さw以下で得られる最大価値
#   ★1次元化するときは w を「大きい方から」回す
#     (小さい方から回すと同じ品物を2回使えてしまう)
# -----------------------------------------------------
def knapsack_01(items, W):
    """items = [(weight, value), ...], W = 容量"""
    dp = [0] * (W + 1)
    for w, v in items:
        for cap in range(W, w - 1, -1):     # ★逆順
            dp[cap] = max(dp[cap], dp[cap - w] + v)
    return dp[W]


# -----------------------------------------------------
# (2) 個数無制限ナップサック: 各品物を何回でも使える
#   違いは1箇所だけ: w を「小さい方から」回す
#   (同じ品物の再利用を許すから正順でよい)
# -----------------------------------------------------
def knapsack_unbounded(items, W):
    dp = [0] * (W + 1)
    for w, v in items:
        for cap in range(w, W + 1):         # ★正順
            dp[cap] = max(dp[cap], dp[cap - w] + v)
    return dp[W]


# -----------------------------------------------------
# (3) LIS (最長増加部分列) O(N log N)
#   lis[i] = 「長さ i+1 の増加列を作れる、最小の末尾の値」
#   lis は常にソート済みになる → 各要素の置き場所を二分探索
#
#   狭義単調増加 (a < b)    : bisect_left
#   広義単調増加 (a <= b)   : bisect_right に替えるだけ
# -----------------------------------------------------
def lis_length(a):
    lis = []
    for x in a:
        pos = bisect_left(lis, x)
        if pos == len(lis):
            lis.append(x)       # 今までのどの末尾より大きい → 延長
        else:
            lis[pos] = x        # 同じ長さで、より小さい末尾に改善
    return len(lis)


# -----------------------------------------------------
# (4) 部分和問題: 「和がちょうどSになる選び方はあるか」
#   dp[s] = 和sを作れるか (bool)
#   0/1ナップサック同様、各要素1回なら逆順で回す
# -----------------------------------------------------
def subset_sum(a, S):
    dp = [False] * (S + 1)
    dp[0] = True                 # 何も選ばなければ和0
    for x in a:
        for s in range(S, x - 1, -1):   # ★各要素1回なので逆順
            if dp[s - x]:
                dp[s] = True
    return dp[S]

