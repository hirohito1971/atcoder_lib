# ---------------- 使用例 ----------------
if __name__ == "__main__":
    items = [(3, 30), (4, 50), (5, 60)]
    print(knapsack_01(items, 8))          # 90 (3+5)
    print(knapsack_unbounded(items, 8))   # 100 (4+4)
    print(lis_length([3, 1, 4, 1, 5, 9, 2, 6]))   # 4 (1,4,5,9 など)
    print(subset_sum([3, 34, 4, 12, 5, 2], 9))    # True (4+5)
