# =====================================================
# 二分探索の型 (めぐる式 + bisect)
# =====================================================
# ★このフォルダ(snippets/)の方針:
#   コピペ用ではなく「コンテスト前に見返して、手で書けるか
#   確認する」ための備忘録。短いが事故りやすいものを置く。
#
# 二分探索は3種類を区別する:
#   (1) ソート済み配列から値を探す → bisectモジュール (自作しない!)
#   (2) 「答えで二分探索」(判定問題に変換) → めぐる式 ★これが本体
#   (3) 実数の二分探索 → 回数固定ループ
# =====================================================

from bisect import bisect_left, bisect_right


# -----------------------------------------------------
# (1) bisect: ソート済み配列への検索は自作せずこれ
# -----------------------------------------------------
def bisect_cheatsheet():
    a = [1, 3, 3, 3, 7, 9]   # ソート済みであること!

    # bisect_left(a, x)  : x を入れられる一番左の位置
    #                    = 「x未満の要素の個数」
    # bisect_right(a, x) : x を入れられる一番右の位置
    #                    = 「x以下の要素の個数」
    print(bisect_left(a, 3))    # 1  (3未満は1個)
    print(bisect_right(a, 3))   # 4  (3以下は4個)

    # 頻出の言い換え (これを口で言えるようにする):
    #   xの個数           = bisect_right - bisect_left
    #   x以上の最小の位置  = bisect_left(a, x)
    #   xより大きい最小の位置 = bisect_right(a, x)
    print(bisect_right(a, 3) - bisect_left(a, 3))   # 3の個数 = 3


# -----------------------------------------------------
# (2) めぐる式二分探索: 「答えで二分探索」の型
# -----------------------------------------------------
# 考え方:
#   「答えは x 以下にできるか?」のような判定関数 is_ok(x) を作ると、
#   is_ok は どこかを境に False...False True...True と単調になる。
#   その境界を求めるのが二分探索。
#
# 不変条件: ok は常に is_ok=True 側、ng は常に False 側。
#   → 初期値は「絶対にTrueな値」「絶対にFalseな値」を
#     ★範囲の1つ外側★に置く (ここを内側に置くのが事故の元)
#
# whileの条件 abs(ok - ng) > 1 :
#   okとngが隣り合ったら境界確定、で終了。
#   ok < ng でも ok > ng でも同じコードで動くのがめぐる式の美点。
# -----------------------------------------------------
def meguru_bisect(ng, ok, is_ok):
    while abs(ok - ng) > 1:
        mid = (ok + ng) // 2
        if is_ok(mid):
            ok = mid       # midがOK側 → ok境界をmidまで寄せる
        else:
            ng = mid
    return ok              # 「条件を満たす側のギリギリ」が返る


def example_meguru():
    # 例:「長さLの丸太K本以上を切り出せる最大のLは?」タイプ
    logs = [8, 5, 10]
    K = 5

    def is_ok(L):
        # 長さLで切ると何本取れるか >= K ?
        return sum(x // L for x in logs) >= K

    # L=1なら確実にOK(=ok側), L=max+1は確実にNG(=ng側)
    ans = meguru_bisect(ng=max(logs) + 1, ok=1, is_ok=is_ok)
    print(ans)   # 4 (8//4 + 5//4 + 10//4 = 2+1+2 = 5本)


# -----------------------------------------------------
# (3) 実数の二分探索: 「差が小さくなるまで」ではなく回数固定
#     100回回せば区間は 2^-100 倍。精度で悩まないのがコツ
# -----------------------------------------------------
def real_bisect(lo, hi, is_ok, times=100):
    for _ in range(times):
        mid = (lo + hi) / 2
        if is_ok(mid):
            hi = mid
        else:
            lo = mid
    return hi


if __name__ == "__main__":
    bisect_cheatsheet()
    example_meguru()
    # √2 を求める例
    print(real_bisect(0, 2, lambda x: x * x >= 2))   # 1.41421356...
