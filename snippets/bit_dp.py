# =====================================================
# bitDP (集合を整数で表すDP)  ★青向け追加ファイル
# =====================================================
# N <= 20 程度で「訪問済みの集合」「使用済みの集合」を
# 状態に持ちたいとき、集合を N ビットの整数で表す。
#   集合S に要素i が入っているか : S >> i & 1
#   集合S に要素i を追加         : S | (1 << i)
#   全体集合                     : (1 << N) - 1
#
# 計算量の目安: O(2^N * N^2) → N=16〜18あたりが限界ライン
# 「Nが20以下」は bitDP を疑え、が定石。
#
# ビット演算チートシート (体で覚える):
#   S & (1 << i)      iビット目が立っているか (0以外ならTrue)
#   S | (1 << i)      iビット目を立てる
#   S & ~(1 << i)     iビット目を消す
#   S ^ (1 << i)      iビット目を反転
#   bin(S).count("1") 立っているビット数 (Python3.10+なら S.bit_count())
# =====================================================


# -----------------------------------------------------
# 代表例1: 巡回セールスマン問題 (TSP)
#   dp[S][v] = 「訪問済み集合がSで、今vにいる」ときの最小コスト
# -----------------------------------------------------
def tsp(n, dist):
    """
    n    : 都市数
    dist : dist[u][v] = u→vの距離
    戻り値: 都市0を出発し全都市を訪れて0に戻る最小コスト
    """
    INF = float("inf")
    FULL = (1 << n) - 1
    # dp[S][v]: 集合Sを訪問済み、現在地v
    dp = [[INF] * n for _ in range(1 << n)]
    dp[1][0] = 0                     # {0}だけ訪問済み、0にいる

    for S in range(1 << n):          # 集合は昇順に回せば遷移順序が正しい
        for v in range(n):           # (Sが増える方向にしか遷移しないため)
            if dp[S][v] == INF:
                continue
            if not (S >> v & 1):     # vがSに入っていない状態は無効
                continue
            for u in range(n):
                if S >> u & 1:       # 訪問済みの都市には行かない
                    continue
                nS = S | (1 << u)
                nd = dp[S][v] + dist[v][u]
                if nd < dp[nS][u]:
                    dp[nS][u] = nd

    # 全都市訪問後、0に戻るコストを足して最小を取る
    return min(dp[FULL][v] + dist[v][0] for v in range(n))


# -----------------------------------------------------
# 代表例2: マッチング系
#   dp[S] = 「集合Sの人まで処理が終わった」ときの何か
#   「Sの立っているビット数」で"今何番目の処理か"が分かるのがコツ
# -----------------------------------------------------
def count_perfect_matchings(n, compatible):
    """
    n人の男性とn人の女性、compatible[i][j]=1ならペア可。
    全員をペアにする方法の数 (ABC典型)
    dp[S] = 女性の使用済み集合がSのときの場合の数
            (男性は i = popcount(S) 番目まで自動的に決まる)
    """
    dp = [0] * (1 << n)
    dp[0] = 1
    for S in range(1 << n):
        if dp[S] == 0:
            continue
        i = bin(S).count("1")        # 次にペアを決める男性の番号
        if i == n:
            continue
        for j in range(n):
            if compatible[i][j] and not (S >> j & 1):
                dp[S | (1 << j)] += dp[S]
    return dp[(1 << n) - 1]


# ---------------- 使用例 ----------------
if __name__ == "__main__":
    dist = [
        [0, 3, 1, 4],
        [3, 0, 6, 2],
        [1, 6, 0, 5],
        [4, 2, 5, 0],
    ]
    print(tsp(4, dist))   # 11 (0→2→3→1→0 = 1+5+2+3)

    compat = [
        [1, 1, 0],
        [0, 1, 1],
        [1, 0, 1],
    ]
    print(count_perfect_matchings(3, compat))   # 2 ((0-0,1-1,2-2) と (0-1,1-2,2-0))
