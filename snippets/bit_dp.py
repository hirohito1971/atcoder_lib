# =====================================================
# bitDP (状態を整数のビットで表すDP)  ★青向け追加ファイル
# =====================================================
# ビットの使い方は2種類ある。mask が「何を表すか」を先に決めること。
#
#   (A) 集合DP       : mask = 「使い終わった要素の集合」
#                      N <= 20 程度。代表例1, 2
#   (B) 行ごとのbitDP: mask = 「1行の各マスの状態 (白/黒など)」
#                      幅 W <= 10 程度。上から1行ずつ決め、直前の行だけ持ち越す。代表例3
#
# (A) 集合DP
#   集合S に要素i が入っているか : S >> i & 1
#   集合S に要素i を追加         : S | (1 << i)
#   全体集合                     : (1 << N) - 1
#   計算量の目安: O(2^N * N^2) → N=16〜18あたりが限界ライン
#   「Nが20以下」は bitDP を疑え、が定石。
#
# (B) 行ごとのbitDP
#   「H, W が小さい (<= 7〜10) グリッド」で、条件が隣り合う行の間でしか
#   効かないとき。全マスの 2^(HW) は無理でも、1行の 2^W なら回せる。
#   計算量の目安: O(H * 4^W) (前の行 2^W × 今の行 2^W)
#
# ビット演算チートシート (体で覚える):
#   S & (1 << i)      iビット目が立っているか (0以外ならTrue)
#   S | (1 << i)      iビット目を立てる
#   S & ~(1 << i)     iビット目を消す
#   S ^ (1 << i)      iビット目を反転
#   bin(S).count("1") 立っているビット数 (Python3.10+なら S.bit_count())
#   (A & B) == A      A が B に含まれる (A ⊆ B)
#   ~A & full         W ビットの範囲で反転 (full = (1 << W) - 1)
#   A & (A >> 1)      隣り合う2ビットが両方立っている場所
#
# ★注意1: 演算子の優先順位。& | ^ は == より弱い!
#   NG: A & B == C   → A & (B == C) と読まれる
#   OK: (A & B) == C
#   ビット演算を比較と並べるときは「必ず括弧」。(ABC424-D で2回落ちた)
#
# ★注意2: Python の ~ は負の数になる (~5 == -6)。
#   端の外まで1が立つので、W ビットで使うときは必ず & full を取る。
#
# ★注意3: not はビット演算ではない。not A は True/False を返すだけ。
#   ビットの反転は ~A。
# =====================================================


# -----------------------------------------------------
# 代表例1: 巡回セールスマン問題 (TSP)
#   dp[S][v] = 「訪問済み集合がSで、今vにいる」ときの最小コスト
# -----------------------------------------------------
def tsp(n, dist):
    """
    n    : 都市数
    dist : dist[u][v] = u→vの距離
    戻り値: 都市0を出発し全都市を訪れて0に戻る最小コスト
    """
    INF = float("inf")
    FULL = (1 << n) - 1
    # dp[S][v]: 集合Sを訪問済み、現在地v
    dp = [[INF] * n for _ in range(1 << n)]
    dp[1][0] = 0                     # {0}だけ訪問済み、0にいる

    for S in range(1 << n):          # 集合は昇順に回せば遷移順序が正しい
        for v in range(n):           # (Sが増える方向にしか遷移しないため)
            if dp[S][v] == INF:
                continue
            if not (S >> v & 1):     # vがSに入っていない状態は無効
                continue
            for u in range(n):
                if S >> u & 1:       # 訪問済みの都市には行かない
                    continue
                nS = S | (1 << u)
                nd = dp[S][v] + dist[v][u]
                if nd < dp[nS][u]:
                    dp[nS][u] = nd

    # 全都市訪問後、0に戻るコストを足して最小を取る
    return min(dp[FULL][v] + dist[v][0] for v in range(n))


# -----------------------------------------------------
# 代表例2: マッチング系
#   dp[S] = 「集合Sの人まで処理が終わった」ときの何か
#   「Sの立っているビット数」で"今何番目の処理か"が分かるのがコツ
# -----------------------------------------------------
def count_perfect_matchings(n, compatible):
    """
    n人の男性とn人の女性、compatible[i][j]=1ならペア可。
    全員をペアにする方法の数 (ABC典型)
    dp[S] = 女性の使用済み集合がSのときの場合の数
            (男性は i = popcount(S) 番目まで自動的に決まる)
    """
    dp = [0] * (1 << n)
    dp[0] = 1
    for S in range(1 << n):
        if dp[S] == 0:
            continue
        i = bin(S).count("1")        # 次にペアを決める男性の番号
        if i == n:
            continue
        for j in range(n):
            if compatible[i][j] and not (S >> j & 1):
                dp[S | (1 << j)] += dp[S]
    return dp[(1 << n) - 1]


# -----------------------------------------------------
# 代表例3: 行ごとのbitDP (グリッドを上から1行ずつ決める)
#   使用例: ABC424-D (2x2 Erasing 2)
#     黒を白に塗り替えて「全部黒の 2×2」をなくす最小の塗り替え数
#
#   dp[mask] = ここまでの行を決めて、今の行の色が mask のときの最小コスト
#              (mask のビット = 白)
#
#   部品 (orig = 元の行の白, p = 前の行, c = 今の行):
#     c が選べるか (元の白を黒にしない) : (orig & c) == orig
#     その行のコスト (新しく白にした数) : (c ^ orig).bit_count()
#     2行とも黒の列                     : both = ~(p | c) & full
#     全部黒の 2×2 がないか             : (both & (both >> 1)) == 0
#
#   見落としやすい観察:
#     - 左上から貪欲に塗るのはダメ (1マスで複数の 2×2 を潰せる場所を見逃す)
#     - 条件が隣り合う行の間でしか効かない → 持ち越すのは直前の1行だけ
#
#   実測: ABC424-D (T <= 100, H, W <= 7) PyPy で 197 ms
# -----------------------------------------------------
def to_mask(s, white='.'):
    """行の文字列 → 白のマスにビットが立った整数 (左の列が上位ビット)"""
    m = 0
    for ch in s:
        m = m * 2 + (ch == white)
    return m


def min_repaint_no_black_2x2(grid):
    """
    grid : 文字列のリスト ('.' = 白, '#' = 黒)
    戻り値: 全部黒の 2×2 をなくすのに必要な、黒→白の最小塗り替え数
    """
    W = len(grid[0])
    full = (1 << W) - 1
    INF = 10 ** 18

    # 1行目: 選べる mask はそのまま初期値
    orig = to_mask(grid[0])
    dp = {}
    for mask in range(1 << W):
        if (orig & mask) == orig:              # 元の白を黒にしない
            dp[mask] = (mask ^ orig).bit_count()

    # 2行目以降: 前の行 p → 今の行 c
    for s in grid[1:]:
        orig = to_mask(s)
        cands = [c for c in range(1 << W) if (orig & c) == orig]   # p に依らないので先に作る
        ndp = {}
        for p, v in dp.items():
            for c in cands:
                both = ~(p | c) & full         # 2行とも黒の列
                if (both & (both >> 1)) == 0:  # 全部黒の 2×2 なし → 遷移OK
                    nv = v + (c ^ orig).bit_count()
                    if nv < ndp.get(c, INF):
                        ndp[c] = nv
        dp = ndp

    return min(dp.values())


# ---------------- 使用例 ----------------
if __name__ == "__main__":
    dist = [
        [0, 3, 1, 4],
        [3, 0, 6, 2],
        [1, 6, 0, 5],
        [4, 2, 5, 0],
    ]
    print(tsp(4, dist))   # 11 (0→2→3→1→0 = 1+5+2+3)

    compat = [
        [1, 1, 0],
        [0, 1, 1],
        [1, 0, 1],
    ]
    print(count_perfect_matchings(3, compat))   # 2 ((0-0,1-1,2-2) と (0-1,1-2,2-0))

    grid = [
        "####.",
        "##.##",
        "#####",
        ".####",
        "##.#.",
    ]
    print(min_repaint_no_black_2x2(grid))   # 3 (ABC424-D サンプル1)
    print(min_repaint_no_black_2x2(["..", ".."]))   # 0