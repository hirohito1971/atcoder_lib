# =============================================================
# 辞書順列挙 DFS（enumerate_dfs）
# 条件を満たす列を「すべて」「辞書順で」出力する型の定型。
# 値を返す再帰ではなく、外部の out / cur を書き換える
# 「副作用だけの再帰」である点が最大の違い。
# -------------------------------------------------------------
# 注意（この2つを落とすと必ず壊れる）
#   * 使い回すバッファは、記録の瞬間にスナップショットを取る。
#     cur を1本使い回す設計を選んだ時点で out.append(cur) は
#     バグる。参照が並ぶだけで、最後の cur の中身が全行に化ける。
#     out.append(" ".join(map(str, cur)))  か cur[:] でコピー。
#     エラーが出ないぶん発見が遅れる。
#   * 書いたら戻す。各層は「自分が触った位置だけ 0 に戻す」責任を
#     持つ。これで「dfs(i, ...) に入った時点で位置 i 以降は 0」
#     という不変条件が保たれ、層をまたいだ状態の漏れが構造的に
#     起きなくなる。この不変条件があるおかげで、途中で解が確定
#     したとき（残り 0 など）に末尾を 0 埋めせずそのまま出せる。
# -------------------------------------------------------------
# 設計の型
#   1. 状態を (深さ, 残り) の2つに畳む。列そのものは状態に含めない
#      （cur を使い回すので引数で渡さない）
#   2. 各深さで値を昇順に試す。これがそのまま辞書順になる。
#      あとからソートは不要
#   3. 出口を3つ意識する
#        (a) 残りが 0 になった → その場で確定、深さを進めない
#        (b) 最終位置に到達  → ループせず O(1) 判定
#        (c) ループを回し終えた → 後片付けして return
#   4. 出力は溜めて最後に1回 sys.stdout.write("\n".join(out))
# -------------------------------------------------------------
# 変数を決める順序の選び方
#   出力が (A_1,...,A_N) の辞書順なら、A_1 から決める。DFS で
#   変数を決める順序は、そのまま出力順のキーの優先順位になる。
#   「最後に係数 1 の変数を残せば行き止まり枝が消えて効率がよい」
#   のは事実だが、それをやると出力順が壊れて最後に全解ソートが
#   必要になり、全解をメモリに持つ羽目になる。
#   効率より辞書順を取り、行き止まりは枝刈りで潰す。
# -------------------------------------------------------------
# 計算量の見積もり方
#   「解の個数 <= X」という制約が付く問題では、その制約が入力側を
#   強く縛っている。例えば下の coefficient_stair は N=10 なら
#   K<=64 でないと解が 3*10^5 個を超える。無駄枝の量も一緒に
#   抑えられるので、素直な DFS で通ることが多い。
#   最悪ケースは「解の個数がちょうど上限になる入力」を DP で
#   逆算して作り、手元で回して確かめる。
# =============================================================

import sys


# -------------------------------------------------------------
# 基本形: sum(i * A_i for i in 1..N) == K を満たす非負整数列を
#         すべて辞書順に列挙する
#         （ABC473-D "Coefficient Stair" / N<=10, K<=2*10^5）
# -------------------------------------------------------------
def coefficient_stair(N, K):
    """係数 (1,2,...,N) の重み付き和が K になる列を辞書順に全列挙。

    戻り値は行文字列のリスト（そのまま "\\n".join で出せる）。
    """
    out = []
    cur = [0] * N

    def dfs(i, r):  # i: これから決める位置(1-indexed), r: 残り
        if r == 0:  # 出口(a) 以降すべて 0 で確定
            out.append(" ".join(map(str, cur)))
            return
        if i == N:  # 出口(b) 最終位置はループ不要
            if r % N == 0:
                cur[N - 1] = r // N
                out.append(" ".join(map(str, cur)))
                cur[N - 1] = 0  # 後片付け
            return  # 割り切れなければここで打ち切り
        for a in range(r // i + 1):  # 出口(c)
            cur[i - 1] = a
            dfs(i + 1, r - i * a)
        cur[i - 1] = 0  # 後片付け

    dfs(1, K)
    return out


# -------------------------------------------------------------
# 高速化版: 最終2位置の係数が N-1, N と連続であることを使う。
#   N | r - (N-1)*a  <=>  a ≡ -r (mod N)
# なので深さ N-1 で a を 0 から全部試さず、a = (-r) % N から
# ステップ N の等差数列で回す。探索したノードが全部解になる。
# 手元計測 (N=10, K=64, 296320行): 基本形 1.05s -> 本版 0.70s
# 制約が緩い（解が 10^6 個規模）ときに効く。
# -------------------------------------------------------------
def coefficient_stair_fast(N, K):
    if N == 1:
        return [str(K)]
    out = []
    cur = [0] * N

    def dfs(i, r):
        if r == 0:
            out.append(" ".join(map(str, cur)))
            return
        if i == N - 1:
            a = (-r) % N
            while (N - 1) * a <= r:
                cur[N - 2] = a
                cur[N - 1] = (r - (N - 1) * a) // N
                out.append(" ".join(map(str, cur)))
                a += N
            cur[N - 2] = 0
            cur[N - 1] = 0
            return
        for a in range(r // i + 1):
            cur[i - 1] = a
            dfs(i + 1, r - i * a)
        cur[i - 1] = 0

    dfs(1, K)
    return out


# -------------------------------------------------------------
# 変形1: 各要素に上限がある場合
#   sum(A_i) == K, 0 <= A_i <= limits[i]
# 上限を掛けるのはループの range だけ。骨格は変わらない。
# 「残り 0 で即確定」は使えなくなる点に注意（残りを 0 にしても
# 後続を 0 で埋めてよいとは限らない…この例では埋めてよいので
# 早期確定は生きているが、下限制約がある問題では消える）
# -------------------------------------------------------------
def bounded_sum(N, K, limits):
    """和が K の非負整数列を辞書順に全列挙（各要素に上限あり）。"""
    out = []
    cur = [0] * N
    # suf[i] = 位置 i..N-1 で作れる和の最大値（枝刈り用）
    suf = [0] * (N + 1)
    for i in range(N - 1, -1, -1):
        suf[i] = suf[i + 1] + limits[i]

    def dfs(i, r):  # i: 0-indexed
        if i == N:
            if r == 0:
                out.append(" ".join(map(str, cur)))
            return
        if r > suf[i]:  # 残りが大きすぎて到達不能
            return
        for a in range(min(r, limits[i]) + 1):
            cur[i] = a
            dfs(i + 1, r - a)
        cur[i] = 0

    dfs(0, K)
    return out


# -------------------------------------------------------------
# 変形2: 単調非減少な列（重複組合せ）を辞書順に
#   1 <= A_1 <= A_2 <= ... <= A_N <= M
# 「前の値」を引数で持ち回るだけ。cur の扱いは同じ。
# 個数が少ないなら itertools.combinations_with_replacement で
# 済む。DFS にするのは途中で枝刈りしたいときだけ。
# -------------------------------------------------------------
def nondecreasing(N, M):
    out = []
    cur = [0] * N

    def dfs(i, lo):  # i: 0-indexed, lo: 使える最小値
        if i == N:
            out.append(" ".join(map(str, cur)))
            return
        for v in range(lo, M + 1):
            cur[i] = v
            dfs(i + 1, v)
        cur[i] = 0

    dfs(0, 1)
    return out


# -------------------------------------------------------------
# 提出時の形（テンプレートに埋める）
# -------------------------------------------------------------
def main():
    it = iter(sys.stdin.buffer.read().split())
    ni = lambda: int(next(it))

    N, K = ni(), ni()
    out = coefficient_stair(N, K)
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()